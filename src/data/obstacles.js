// The 20 Spartan Sprint checkpoints (female standards) and how each one is
// scored from the workout log.
//
// Each obstacle has a single metric. The metric's value is the best result
// across its `sources`, where each source reads one exercise:
//   calc 'e1rm'   – estimated 1-rep max (Epley) from any logged set
//   calc 'weight' – heaviest weight lifted for at least `minReps` reps
//   calc 'carry'  – heaviest per-hand load carried at least `minDistance` m
//   calc 'value'  – a self-test result (set.reps)
// `factor` converts the source into the obstacle's unit (default 1).
//
// survive = minimum to get through (amber); thrive = race ready (green).
// For better: 'lower' (run times) the comparison is reversed.
//
// Gym-lift thresholds are proxies — they estimate the strength an obstacle
// needs, not the obstacle itself. Re-test the real thing whenever possible.

